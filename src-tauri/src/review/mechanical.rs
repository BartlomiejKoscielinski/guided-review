    /// A hunk from diff-style lines ("-old", "+new", " ctx") starting at line `start`.
    fn hunk(start: u32, lines: &[&str]) -> Hunk {
        let (mut old_no, mut new_no) = (start, start);
        let lines = lines
            .iter()
            .map(|raw| {
                let (mark, text) = raw.split_at(1);
                let kind = match mark {
                    "-" => LineKind::Del,
                    "+" => LineKind::Add,
                    _ => LineKind::Ctx,
                };
                let old = (kind != LineKind::Add).then(|| {
                    old_no += 1;
                    old_no - 1
                });
                let new = (kind != LineKind::Del).then(|| {
                    new_no += 1;
                    new_no - 1
                });
                Line {
                    kind,
                    old_no: old,
                    new_no: new,
                    text: text.to_owned(),
                    emphasis: Vec::new(),
                    staged: None,
                }
            })
            .collect();
        Hunk {
            id: "h".into(),
            old_start: start,
            old_lines: 0,
            new_start: start,
            new_lines: 0,
            header: String::new(),
            lines,
            file_level: false,
            staged_differs: false,
            mechanical: None,
        }
    }

    fn file(path: &str, status: FileStatus, hunks: Vec<Hunk>) -> FileDiff {
        FileDiff {
            old_path: Some(path.into()),
            new_path: (status != FileStatus::Deleted).then(|| path.into()),
            status,
            binary: false,
            mode_change: None,
            additions: 0,
            deletions: 0,
            layer: Layer::Other,
            hunks,
            line_staging: true,
        }
    }

