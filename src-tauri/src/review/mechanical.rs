//! Mechanical hunks without AI (F-05.5, 05 › Mechanical hunks, M3 decision 3): first match
//! wins. Mechanical hunks are proposed for Skim and listed in the plan input.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::git::model::{FileDiff, FileStatus, Hunk, LineKind};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum MechanicalReason {
    Generated,
    Whitespace,
    PackageBump,
    ResxKeyAdded,
}

const GENERATED_SUFFIXES: [&str; 3] = [".g.cs", ".g.i.cs", ".designer.cs"];
const GENERATED_FOLDERS: [&str; 2] = ["obj", "bin"];
const PACKAGE_ELEMENTS: [&str; 2] = ["<packagereference ", "<packageversion "];

/// Sets `Hunk.mechanical` on every text hunk of the file; file-level hunks (F-05.7) stay `None`.
pub fn mark(file: &mut FileDiff) {
    let path = file
        .new_path
        .as_deref()
        .or(file.old_path.as_deref())
        .unwrap_or_default()
        .to_owned();
    let first = first_line(file).map(str::to_owned);
    for hunk in &mut file.hunks {
        hunk.mechanical = classify(&path, first.as_deref(), hunk);
    }
}

/// The reason a hunk is mechanical, or `None`. `first_line` is the file's first line when known.
pub fn classify(path: &str, first_line: Option<&str>, hunk: &Hunk) -> Option<MechanicalReason> {
    if hunk.file_level {
        return None;
    }
    let lower = path.to_lowercase();
    if is_generated(&lower, first_line) {
        Some(MechanicalReason::Generated)
    } else if is_whitespace_only(hunk) {
        Some(MechanicalReason::Whitespace)
    } else if (lower.ends_with(".csproj") || lower.ends_with(".props")) && is_package_bump(hunk) {
        Some(MechanicalReason::PackageBump)
    } else if lower.ends_with(".resx") && is_resx_key_add(hunk) {
        Some(MechanicalReason::ResxKeyAdded)
    } else {
        None
    }
}

/// Line 1 of the new version (the old one for a deletion), when a hunk starts there.
fn first_line(file: &FileDiff) -> Option<&str> {
    let deleted = file.status == FileStatus::Deleted;
    file.hunks
        .iter()
        .flat_map(|h| &h.lines)
        .find(|l| {
            if deleted {
                l.old_no == Some(1)
            } else {
                l.new_no == Some(1)
            }
        })
        .map(|l| l.text.as_str())
}

fn is_generated(lower_path: &str, first_line: Option<&str>) -> bool {
    let mut parts: Vec<&str> = lower_path.split(['/', '\\']).collect();
    let name = parts.pop().unwrap_or_default();
    GENERATED_SUFFIXES.iter().any(|s| name.ends_with(s))
        || parts.iter().any(|f| GENERATED_FOLDERS.contains(f))
        || first_line.is_some_and(|l| l.contains("<auto-generated"))
}

fn changed(hunk: &Hunk, kind: LineKind) -> impl Iterator<Item = &str> {
    hunk.lines
        .iter()
        .filter(move |l| l.kind == kind)
        .map(|l| l.text.as_str())
}

fn collapse(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn is_whitespace_only(hunk: &Hunk) -> bool {
    let normalized = |kind| -> Vec<String> {
        changed(hunk, kind)
            .map(collapse)
            .filter(|l| !l.is_empty())
            .collect()
    };
    normalized(LineKind::Del) == normalized(LineKind::Add)
}

/// The element with its `Version` value emptied, or `None` if the line isn't a package element
/// with a `Version` attribute.
fn without_version(line: &str) -> Option<String> {
    let text = collapse(line);
    let lower = text.to_ascii_lowercase();
    if !PACKAGE_ELEMENTS.iter().any(|e| lower.starts_with(e)) {
        return None;
    }
    // ASCII lowercasing keeps byte offsets, so positions found in `lower` index `text`.
    let attr = lower.find(" version=")? + " version=".len();
    let quote = *text.as_bytes().get(attr)?;
    if quote != b'"' && quote != b'\'' {
        return None;
    }
    let end = attr + 1 + text[attr + 1..].find(char::from(quote))?;
    Some(format!("{}{}", &text[..attr + 1], &text[end..]))
}

fn is_package_bump(hunk: &Hunk) -> bool {
    let removed: Vec<&str> = changed(hunk, LineKind::Del).collect();
    let added: Vec<&str> = changed(hunk, LineKind::Add).collect();
    !removed.is_empty()
        && removed.len() == added.len()
        && removed.iter().zip(&added).all(|(old, new)| {
            matches!((without_version(old), without_version(new)), (Some(a), Some(b)) if a == b)
        })
}

fn is_resx_key_add(hunk: &Hunk) -> bool {
    let mut inside = false;
    let mut any = false;
    for line in &hunk.lines {
        let text = line.text.trim();
        match line.kind {
            LineKind::Del => return false,
            LineKind::Ctx if inside => return false,
            LineKind::Ctx => {}
            LineKind::Add if inside => inside = !text.contains("</data>"),
            LineKind::Add if text.is_empty() => {}
            LineKind::Add => {
                if !(text.starts_with("<data ") && text.contains("name=")) {
                    return false;
                }
                any = true;
                inside = !(text.contains("</data>") || text.ends_with("/>"));
            }
        }
    }
    any && !inside
}

