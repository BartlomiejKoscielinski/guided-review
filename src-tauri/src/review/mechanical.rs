    #[test]
    fn f05_5_auto_generated_header_marks_every_hunk_of_the_file() {
        let header = hunk(1, &["//------", "// <auto-generated>", "-old", "+new"]);
        let first = "//------";
        assert_eq!(classify("src/App/Gen.cs", Some(first), &header), None);
        let header = hunk(1, &["// <auto-generated />", "-old", "+new"]);
        let later = hunk(40, &[" x", "-y", "+z"]);
        let mut f = file("src/App/Gen.cs", FileStatus::Modified, vec![header, later]);
        mark(&mut f);
        assert!(f.hunks.iter().all(|h| h.mechanical == Some(Generated)));
    }

    #[test]
    fn f05_5_deleted_file_reads_the_old_first_line() {
        let gone = hunk(1, &["-// <auto-generated>", "-class A {}"]);
        let mut f = file("src/App/Gen.cs", FileStatus::Deleted, vec![gone]);
        mark(&mut f);
        assert_eq!(f.hunks[0].mechanical, Some(Generated));
    }

    #[test]
    fn f05_5_file_level_hunks_are_not_classified() {
        let mut h = hunk(0, &[]);
        h.file_level = true;
        assert_eq!(classify("src/App/obj/x.g.cs", None, &h), None);
    }

    #[test]
    fn f05_5_mark_without_a_known_first_line_keeps_ordinary_hunks() {
        let mut f = file(
            "src/App/ViewModels/LoginViewModel.cs",
            FileStatus::Modified,
            vec![hunk(30, &[" a", "-b", "+c"]), hunk(60, &["-  d", "+d"])],
        );
        mark(&mut f);
        assert_eq!(f.hunks[0].mechanical, None);
        assert_eq!(f.hunks[1].mechanical, Some(Whitespace));
    }

