//! Mechanical hunks on real `git diff` output (F-05.5, docs/05 › Mechanical hunks): the four
//! kinds are detected without AI on fixture repositories, through the production path
//! (`diff::range_files` + `diff::range_file_diff`), and nothing else is marked. Synthetic data
//! only (ADR-019); paths carry spaces and Polish characters.
#![allow(clippy::unwrap_used, clippy::expect_used, reason = "tests")]

use crate::fixture_repo;

use fixture_repo::FixtureRepo;
use guided_review_lib::git::Git;
use guided_review_lib::git::diff;
use guided_review_lib::git::model::FileDiff;
use guided_review_lib::os::process::Cancel;
use guided_review_lib::review::mechanical::MechanicalReason;
use guided_review_lib::review::mechanical::MechanicalReason::{
    Generated, PackageBump, ResxKeyAdded, Whitespace,
};

/// Every file of `base → head` with its hunks, the way the plan and the steps read them.
async fn files(repo: &FixtureRepo, base: &str, head: &str) -> Vec<FileDiff> {
    let git = Git::new(None, &repo.path);
    let cancel = Cancel::new();
    let mut out = Vec::new();
    for file in diff::range_files(&git, base, head, &cancel).await.unwrap() {
        out.push(
            diff::range_file_diff(&git, base, head, &file, &cancel)
                .await
                .unwrap(),
        );
    }
    out
}

/// `Hunk.mechanical` of every hunk of the file at `path`, in diff order.
fn reasons(files: &[FileDiff], path: &str) -> Vec<Option<MechanicalReason>> {
    let file = files
        .iter()
        .find(|f| f.new_path.as_deref().or(f.old_path.as_deref()) == Some(path))
        .unwrap_or_else(|| panic!("{path} is not in the diff"));
    file.hunks.iter().map(|h| h.mechanical).collect()
}

fn numbered(prefix: &str, count: usize) -> String {
    (1..=count)
        .map(|i| format!("    // {prefix} {i}\n"))
        .collect()
}

const VIEW_MODEL: &str = "src/App/ViewModels/Zażółć ViewModel.cs";
const SERVICE: &str = "src/App/Services/Upload Service.cs";
const CSPROJ: &str = "src/App/Mobile App.csproj";
const PROPS: &str = "Directory.Packages.props";
const RESX: &str = "src/App/Strings/Zasoby ąę.resx";

fn csproj(toolkit: &str, serilog: &str, framework: &str) -> String {
    format!(
        "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup>\n    <TargetFramework>{framework}</TargetFramework>\n  </PropertyGroup>\n  <ItemGroup>\n    <PackageReference Include=\"CommunityToolkit.Mvvm\" Version=\"{toolkit}\" />\n    <PackageReference Include=\"Serilog\" Version=\"{serilog}\" />\n  </ItemGroup>\n</Project>\n"
    )
}

fn props(polly: &str, refit: &str) -> String {
    format!(
        "<Project>\n  <ItemGroup>\n    <PackageVersion Include=\"Polly\" Version=\"{polly}\" />\n    <PackageVersion Include=\"Refit\" Version=\"{refit}\" />\n  </ItemGroup>\n</Project>\n"
    )
}

fn resx(blocks: &[(&str, &str)]) -> String {
    let data: String = blocks
        .iter()
        .map(|(name, value)| {
            format!(
                "  <data name=\"{name}\" xml:space=\"preserve\">\n    <value>{value}</value>\n  </data>\n"
            )
        })
        .collect();
    format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<root>\n  <resheader name=\"resmimetype\">\n    <value>text/microsoft-resx</value>\n  </resheader>\n{data}</root>\n"
    )
}

#[tokio::test]
async fn f05_5_real_diff_marks_the_four_mechanical_kinds_and_nothing_else() {
    let repo = FixtureRepo::new("f05-5-kinds");
    // Whitespace only: the whole method re-indented with tabs and trailing blanks.
    repo.write(
        VIEW_MODEL,
        "namespace App;\n\npublic class Vm\n{\n    public void Send()\n    {\n        if (ready)\n        {\n            queue.Enqueue();\n        }\n    }\n}\n",
    );
    repo.write(CSPROJ, &csproj("8.2.2", "3.1.1", "net9.0-android"));
    repo.write(PROPS, &props("8.0.0", "7.0.0"));
    repo.write(
        RESX,
        &resx(&[("Login_Title", "Log in"), ("Login_Hint", "E-mail")]),
    );
    repo.write("src/App/Views/Login.xaml.g.cs", "class A { int x = 1; }\n");
    repo.write(
        "src/App/Gen/Old Api.cs",
        &format!("// <auto-generated>\n{}", numbered("removed client", 10)),
    );
    repo.write("src/App/Logic.cs", "class L { int Add(int a) => a; }\n");
    let base = repo.commit_all("base");

    repo.write(
        VIEW_MODEL,
        "namespace App;\n\npublic class Vm\n{\n\tpublic void Send()\n\t{\n\t\tif (ready)\n\t\t{\n\t\t\tqueue.Enqueue();  \n\t\t}\n\t}\n}\n",
    );
    repo.write(CSPROJ, &csproj("8.3.0", "4.0.0", "net9.0-android"));
    repo.write(PROPS, &props("8.1.0", "7.1.0"));
    repo.write(
        RESX,
        &resx(&[
            ("Login_Title", "Log in"),
            ("Login_Hint", "E-mail"),
            ("Login_Error", "Wrong password"),
            ("Login_Retry", "Try again"),
        ]),
    );
    repo.write("src/App/Views/Login.xaml.g.cs", "class A { int x = 2; }\n");
    repo.remove("src/App/Gen/Old Api.cs");
    repo.write(
        "src/App/Gen/New Api.cs",
        &format!("// <auto-generated>\n{}", numbered("new client", 3)),
    );
    repo.write("src/App/obj/Debug/App.AssemblyInfo.cs", "[assembly: X]\n");
    repo.write("src/App/Logic.cs", "class L { int Add(int a) => a + 1; }\n");
    let head = repo.commit_all("head");

    let files = files(&repo, &base, &head).await;
    assert_eq!(reasons(&files, VIEW_MODEL), [Some(Whitespace)]);
    assert_eq!(reasons(&files, CSPROJ), [Some(PackageBump)]);
    assert_eq!(reasons(&files, PROPS), [Some(PackageBump)]);
    assert_eq!(reasons(&files, RESX), [Some(ResxKeyAdded)]);
    assert_eq!(
        reasons(&files, "src/App/Views/Login.xaml.g.cs"),
        [Some(Generated)]
    );
    // The first line of the new version (added file) and of the old one (deleted file).
    assert_eq!(reasons(&files, "src/App/Gen/New Api.cs"), [Some(Generated)]);
    assert_eq!(reasons(&files, "src/App/Gen/Old Api.cs"), [Some(Generated)]);
    assert_eq!(
        reasons(&files, "src/App/obj/Debug/App.AssemblyInfo.cs"),
        [Some(Generated)]
    );
    // An ordinary logic change stays out.
    assert_eq!(reasons(&files, "src/App/Logic.cs"), [None]);
}

#[tokio::test]
async fn f05_5_only_the_mechanical_hunks_of_a_mixed_file_are_marked() {
    let repo = FixtureRepo::new("f05-5-mixed");
    let body = |first: &str, last: &str| {
        format!(
            "class Upload {{\n{first}\n{}{last}\n}}\n",
            numbered("filler", 24)
        )
    };
    repo.write(
        SERVICE,
        &body("    int Retries = 3;", "    void Stop() { }"),
    );
    // A package bump next to a new target framework is not a bump.
    repo.write(CSPROJ, &csproj("8.2.2", "3.1.1", "net8.0-android"));
    let base = repo.commit_all("base");

    // Hunk 1 changes behavior, hunk 2 only the spacing, 24 lines apart.
    repo.write(
        SERVICE,
        &body("    int Retries = 5;", "    void   Stop()   {   }"),
    );
    repo.write(CSPROJ, &csproj("8.3.0", "3.1.1", "net9.0-android"));
    let head = repo.commit_all("head");

    let files = files(&repo, &base, &head).await;
    assert_eq!(reasons(&files, SERVICE), [None, Some(Whitespace)]);
    assert_eq!(reasons(&files, CSPROJ), [None]);
}

#[tokio::test]
async fn f05_5_line_endings_and_the_final_newline_are_whitespace_only() {
    let repo = FixtureRepo::new("f05-5-eol");
    repo.write_bytes("src/App/Lf.cs", b"class A\n{\n    int x;\n}\n");
    repo.write_bytes("src/App/NoNewline.cs", b"class B\n{\n    int y;\n}");
    repo.write_bytes("src/App/Edit.cs", b"class C\n{\n    int z;\n}\n");
    let base = repo.commit_all("base");

    repo.write_bytes("src/App/Lf.cs", b"class A\r\n{\r\n    int x;\r\n}\r\n");
    repo.write_bytes("src/App/NoNewline.cs", b"class B\n{\n    int y;\n}\n");
    repo.write_bytes("src/App/Edit.cs", b"class C\r\n{\r\n    int z2;\r\n}\r\n");
    let head = repo.commit_all("head");

    let files = files(&repo, &base, &head).await;
    assert_eq!(reasons(&files, "src/App/Lf.cs"), [Some(Whitespace)]);
    assert_eq!(reasons(&files, "src/App/NoNewline.cs"), [Some(Whitespace)]);
    // A real edit under new line endings is still a change.
    assert_eq!(reasons(&files, "src/App/Edit.cs"), [None]);
}

#[tokio::test]
async fn f05_5_a_rename_without_text_changes_is_not_classified() {
    let repo = FixtureRepo::new("f05-5-rename");
    let body: String = numbered("same", 20);
    repo.write("src/App/Old Name.cs", &body);
    let base = repo.commit_all("base");
    std::fs::create_dir_all(repo.file("src/App/obj")).unwrap();
    repo.git(&["mv", "src/App/Old Name.cs", "src/App/obj/Nowa nazwa.cs"]);
    let head = repo.commit_all("rename");

    // The file-level hunk (F-05.7) stays a plain skim proposal, even under `obj/`.
    let files = files(&repo, &base, &head).await;
    assert!(files[0].hunks.iter().all(|h| h.file_level));
    assert_eq!(reasons(&files, "src/App/obj/Nowa nazwa.cs"), [None]);
}

#[tokio::test]
async fn f05_5_keys_inserted_between_existing_keys_are_still_a_resx_key_addition() {
    let repo = FixtureRepo::new("f05-5-resx-middle");
    repo.write(
        RESX,
        &resx(&[
            ("A_First", "One"),
            ("C_Third", "Three"),
            ("E_Fifth", "Five"),
        ]),
    );
    let base = repo.commit_all("base");
    repo.write(
        RESX,
        &resx(&[
            ("A_First", "One"),
            ("B_Second", "Two"),
            ("C_Third", "Three"),
            ("D_Fourth", "Four"),
            ("E_Fifth", "Five"),
        ]),
    );
    let head = repo.commit_all("head");

    let files = files(&repo, &base, &head).await;
    // Two insertions in one hunk, both only added <data> blocks.
    assert_eq!(reasons(&files, RESX), [Some(ResxKeyAdded)]);
    assert!(
        files[0].hunks[0]
            .lines
            .iter()
            .any(|l| l.text.contains("B_Second"))
    );
    assert!(
        files[0].hunks[0]
            .lines
            .iter()
            .any(|l| l.text.contains("D_Fourth"))
    );
}

#[test]
fn f05_5_the_plan_prompt_proposes_the_detected_hunks_for_skim() {
    // 05 › Mechanical hunks: "Mechanical hunks go to the skim proposal and into the plan input
    // as `mechanical_file`."
    let line = guided_review_lib::claude::prompts::PLAN
        .lines()
        .find(|l| l.contains("{{mechanical_file}}"))
        .expect("the plan prompt names the mechanical_file input");
    assert!(line.to_lowercase().contains("skim"), "{line}");
}
